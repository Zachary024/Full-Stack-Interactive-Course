// Service Worker: offline support via Cache API
// Strategy: precache app shell + all lessons; static = stale-while-revalidate;
// navigation = network-first with cached fallback; /api = network-only.
const VERSION = 'v10';
const CACHE = 'fs-course-' + VERSION;
importScripts('js/modules-data.js');          // defines MODULES (generated by build-content.py)
const PRECACHE = [
  './', 'index.html', 'css/style.css', 'manifest.json',
  'js/modules-data.js', 'js/runner.js', 'js/languages.js', 'js/highlight.js', 'js/quiz.js', 'js/widgets.js', 'js/app.js',
  'vendor/sql/sql-wasm.js', 'vendor/sql/sql-wasm.wasm',
  'assets/icon.svg', 'assets/icon-192.png', 'assets/icon-512.png',
  'modules/glossary.html',
  ...MODULES.map(m => `modules/${m.id}.html`),
];

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then(c => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then(keys => Promise.all(keys.filter(k => k.startsWith('fs-course-') && k !== CACHE).map(k => caches.delete(k))))
      .then(() => self.clients.claim()));
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  const url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== location.origin || url.pathname.startsWith('/api/')) return;

  if (req.mode === 'navigate') {
    event.respondWith(
      fetch(req).then(res => { caches.open(CACHE).then(c => c.put(req, res.clone())); return res; })
        .catch(() => caches.match(req).then(r => r || caches.match('index.html'))));
    return;
  }
  event.respondWith(
    caches.match(req).then(cached => {
      const net = fetch(req).then(res => {
        if (res && res.ok) caches.open(CACHE).then(c => c.put(req, res.clone()));
        return res;
      }).catch(() => cached);
      return cached || net;
    }));
});
